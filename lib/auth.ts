// Tiny auth helper. Cookie value = SHA-256(APP_PASSWORD). If the env var
// rotates, existing cookies stop validating and everyone has to sign in
// again. No accounts, no sessions, no revocation list — just a gate.

export const AUTH_COOKIE = "comal_auth";

export async function authTokenFor(password: string): Promise<string> {
  const bytes = new TextEncoder().encode(password);
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

export function timingSafeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let mismatch = 0;
  for (let i = 0; i < a.length; i++) {
    mismatch |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return mismatch === 0;
}
